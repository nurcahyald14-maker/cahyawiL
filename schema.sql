create table if not exists public.packages (
  id bigint generated by default as identity primary key,
  title text not null,
  price numeric not null default 0,
  description text,
  image_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.gallery (
  id bigint generated by default as identity primary key,
  image_url text not null,
  caption text,
  category text default 'foto',
  created_at timestamptz not null default now()
);

create table if not exists public.team (
  id bigint generated by default as identity primary key,
  name text not null,
  role text not null,
  photo_url text,
  created_at timestamptz not null default now()
);

-- Kolom whatsapp_number, vision, mission sesuai spesifikasi;
-- kolom lain dipakai untuk kontak, media sosial, dan peta.
create table if not exists public.settings (
  id bigint generated by default as identity primary key,
  whatsapp_number text not null,
  vision text,
  mission text,
  address text,
  phone text,
  email text,
  instagram text,
  facebook text,
  maps_embed text
);

-- Log klik booking dari pengunjung
create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  name text not null,
  package_title text,
  booking_date date,
  people int,
  created_at timestamptz not null default now()
);

-- ------------------------------------------------------------
-- Row Level Security
-- Publik: boleh MEMBACA konten & MENAMBAH log booking.
-- Admin (user terautentikasi): boleh mengelola semuanya.
-- ------------------------------------------------------------
alter table public.packages enable row level security;
alter table public.gallery  enable row level security;
alter table public.team     enable row level security;
alter table public.settings enable row level security;
alter table public.bookings enable row level security;

create policy "public read packages" on public.packages for select using (true);
create policy "public read gallery"  on public.gallery  for select using (true);
create policy "public read team"     on public.team     for select using (true);
create policy "public read settings" on public.settings for select using (true);

create policy "admin write packages" on public.packages for all to authenticated using (true) with check (true);
create policy "admin write gallery"  on public.gallery  for all to authenticated using (true) with check (true);
create policy "admin write team"     on public.team     for all to authenticated using (true) with check (true);
create policy "admin write settings" on public.settings for all to authenticated using (true) with check (true);

-- Pengunjung hanya boleh menambah log; membaca/menghapus hanya admin.
create policy "public insert bookings" on public.bookings
  for insert to anon, authenticated
  with check (char_length(name) between 1 and 80 and (people is null or people between 1 and 100));
create policy "admin read bookings"   on public.bookings for select to authenticated using (true);
create policy "admin delete bookings" on public.bookings for delete to authenticated using (true);

